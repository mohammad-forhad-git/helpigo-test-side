    <h2>What we collect</h2>
    <ul>
        <li><strong>Everyone:</strong> name, mobile number, password (stored only as a one-way hash), language, login times and IP addresses for security.</li>
        <li><strong>Customers:</strong> saved addresses, contact details of people you book for, task details, photos of lists, prescriptions and receipts, payments, ratings and messages.</li>
        <li><strong>Helpers:</strong> National ID number and photo, a selfie, gender, a reference contact, payout wallet number, areas, services, earnings, ratings and messages.</li>
    </ul>
    <h2>Why</h2>
    <p>To run tasks, verify helpers, keep payment records, settle disputes, prevent fraud and keep people safe. We do not sell personal data and do not use it for third-party advertising.</p>
    <h2>Who sees what</h2>
    <ul>
        <li>Helpers see a task's area, items and fees before accepting. The drop-off address and phone numbers are shown only to the assigned helper while the task is active.</li>
        <li>Your delivery code is shown only to you.</li>
        <li>ID documents are stored outside the public website and are seen only by Helpigo staff.</li>
        <li>Staff access is limited to what they need and every staff action is logged.</li>
    </ul>
    <h2>How long we keep it</h2>
    <p>Task and payment records: as long as needed for accounting and legal duties. ID documents of rejected helpers: deleted within 90 days. You can ask us to delete your account; records we must keep by law are kept and the rest is removed.</p>
    <h2>Security</h2>
    <p>HTTPS only, hashed passwords, private file storage, login limits, daily backups and access logs.</p>
    <h2>Your rights</h2>
    <p>You can see and correct your details in the app, and ask us for a copy or deletion of your data by contacting support.</p>
